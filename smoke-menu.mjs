import { chromium } from '@playwright/test';
const B = 'http://192.168.3.185:5185';
const b = await chromium.launch();
const p = await b.newPage();
await p.goto(B + '/login', { waitUntil: 'networkidle' });
const inputs = await p.locator('form input').all();
console.log('login inputs:', inputs.length);
await p.locator('input').nth(0).fill('cd-water');
await p.locator('input').nth(1).fill('admin');
await p.locator('input[type="password"]').fill('admin12345');
await p.click('button[type="submit"]');
await p.waitForTimeout(3000);
await p.goto(B + '/service/orders', { waitUntil: 'networkidle' });
await p.waitForTimeout(1500);
const menuText = await p.evaluate(() => document.querySelector('.ant-menu')?.innerText ?? '');
console.log('MENU:', menuText.split('\n').filter(Boolean).join(' | '));
const body = await p.evaluate(() => document.body.innerText.slice(0, 350));
console.log('ORDERS:', body.replace(/\n+/g, ' | '));
await p.goto(B + '/service/stats', { waitUntil: 'networkidle' });
await p.waitForTimeout(1200);
console.log('STATS:', (await p.evaluate(() => document.body.innerText.slice(0, 250))).replace(/\n+/g,' | '));
await p.goto(B + '/service/replace-records', { waitUntil: 'networkidle' });
await p.waitForTimeout(1200);
console.log('RR:', (await p.evaluate(() => document.body.innerText.slice(0, 250))).replace(/\n+/g,' | '));
await b.close();
